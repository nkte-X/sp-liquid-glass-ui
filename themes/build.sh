#!/usr/bin/env bash
# Builds themes/ios-liquid-glass.css = upstream liquid-glass.css + iOS layer.
#   ./themes/build.sh           build from the local snapshot
#   ./themes/build.sh --update  refresh the upstream snapshot first
set -euo pipefail
cd "$(dirname "$0")"

UPSTREAM_URL="https://raw.githubusercontent.com/super-productivity/super-productivity/master/src/assets/themes/liquid-glass.css"

if [[ "${1:-}" == "--update" ]]; then
  curl -sfL "$UPSTREAM_URL" -o src/base-liquid-glass.css
  echo "Updated src/base-liquid-glass.css from upstream master"
fi

{
  cat <<'EOF'
/**
 * Liquid Glass UI — Super Productivity theme
 * https://github.com/nkte-X/sp-liquid-glass-ui
 *
 * Part 1: the built-in "Liquid Glass" theme of Super Productivity,
 *   Copyright (c) 2018 Johannes Millan, MIT License (see NOTICE.md).
 * Part 2: the Liquid Glass UI layer (floating tab bar, glass chrome, sheets,
 *   iOS palette), Copyright (c) 2026 nkte-X,
 *   PolyForm Noncommercial License 1.0.0 (see LICENSE).
 *
 * Install: Settings → Theme → Install theme → pick this file — or install
 * the Liquid Glass UI plugin, which bundles it.
 * Generated by themes/build.sh — edit themes/src/*, not this file.
 */

EOF
  cat src/base-liquid-glass.css
  printf '\n\n'
  cat src/ios-layer.css
} > ios-liquid-glass.css

echo "Built ios-liquid-glass.css ($(wc -c < ios-liquid-glass.css | tr -d ' ') bytes)"
